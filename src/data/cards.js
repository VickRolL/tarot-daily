export function pickRandomCard() {
  const index = Math.floor(Math.random() * MAJOR_ARCANA.length)
  return MAJOR_ARCANA[index]
}

/**
 * 抽到这张牌时，用它的第几条建议（第三十二轮）。
 *
 * ⚠️ 这个函数**只负责选**，不负责记住 —— 抽牌那一刻选出来的下标必须落盘
 * （见 `useDrawState.save`）。若在渲染里现选现用，React 每重渲染一次就换一条，
 * 「今日建议」会变成「每帧建议」：打开完整解读再关掉，字就变了。
 */
export function pickAdviceIndex(card, rand = Math.random) {
  const n = card?.advices?.length ?? 0
  if (!n) return 0
  return Math.min(n - 1, Math.max(0, Math.floor(rand() * n)))
}

/**
 * 取下标的建议文本 —— 越界或缺失一律退回第 0 条，**不返回 undefined**。
 *
 * 为什么要有这一层：`adviceIndex` 是从 localStorage 里读回来的，而那个值可能是
 * 旧版本记录（根本没有这个字段）、也可能是被手改过的（调试时常见）。
 * 一旦某张牌的 advices 被删掉几条，老记录里的下标就越界了 ——
 * 那时页面会渲染出空白，还找不到原因。这里兜住，最坏也只是回退到第 0 条。
 */
export function adviceAt(card, index) {
  const list = card?.advices
  if (!list || !list.length) return ''
  if (Number.isInteger(index) && index >= 0 && index < list.length) return list[index]
  return list[0]
}
